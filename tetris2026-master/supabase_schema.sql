create table if not exists public.key_settings (
    user_id uuid primary key references auth.users(id) on delete cascade,
    p1_left integer not null,
    p1_right integer not null,
    p1_rotate integer not null,
    p1_drop integer not null,
    p2_left integer not null,
    p2_right integer not null,
    p2_rotate integer not null,
    p2_drop integer not null
);

create table if not exists public.board_saves (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    board_data text not null,
    current_shape text not null,
    current_x integer not null,
    current_y integer not null,
    lines integer not null,
    saved_at timestamptz not null default now()
);

create table if not exists public.user_records (
    user_id uuid primary key references auth.users(id) on delete cascade,
    nickname text not null,
    games integer not null default 0,
    wins integer not null default 0,
    updated_at timestamptz not null default now()
);

alter table public.key_settings enable row level security;
alter table public.board_saves enable row level security;
alter table public.user_records enable row level security;

create policy "key settings owner access" on public.key_settings
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "board saves owner access" on public.board_saves
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "user records owner access" on public.user_records
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);